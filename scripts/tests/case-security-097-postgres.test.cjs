test('verifier refuses unbound baseline; reviewed rows pass; row or policy drift fails closed', () => {
  const unbound = A.gate(true).replaceAll(A.j(JSON.parse(A.read(A.reviewedPath))),A.j({candidate_sha256:null,rows_sha256:null}));
  assert.equal(json(unbound).gate_pass,false);
  // The reviewed Production baseline must not accept invented local fixture rows.
  assert.equal(json(A.gate(true)).gate_pass,false);
  const bound = A.gate(true).replaceAll(A.j(JSON.parse(A.read(A.reviewedPath))),A.j({candidate_sha256:A.hash(A.read(A.candidate)),rows_sha256:sql(`SELECT ${'encode(sha256(convert_to(x::text,\'UTF8\')),\'hex\')'} FROM (${A.rows()}) r(x)`)}));
  assert.equal(json(bound).gate_pass,true);
  assert.equal(json('BEGIN; UPDATE cases SET title=\'drift\';'+bound+'ROLLBACK;').gate_pass,false);
  assert.equal(json('BEGIN; DROP POLICY case097_process_update ON cases;'+bound+'ROLLBACK;').gate_pass,false);
});
