test('soft-delete, deleted_by-only tamper and INSERT tombstones are Partner/Admin only', () => {
  for (const table of A.names.filter(n => A.before.tables[n].columns.some(c => c.name==='deleted_at'))) {
    const allowedWriter = ['case_fee_items','case_expense_items'].includes(table)?9:table==='case_time_logs'?3:['case_tasks','case_notes'].includes(table)?5:4;
    deny(allowedWriter,`UPDATE ${table} SET deleted_at=now()`);
    deny(allowedWriter,`UPDATE ${table} SET deleted_by='spoof'`);
    for (const n of [1,2]) assert.equal(run(n,`WITH x AS (UPDATE ${table} SET deleted_at=now(),deleted_by='Partner' RETURNING id) SELECT count(*) FROM x`),'1');
  }
  deny(5,"INSERT INTO case_tasks(case_id,deleted_at) VALUES(1,now())");
  // A real restore is checked against OLD.deleted_at, not simply a NULL new value.
  sql("UPDATE case_tasks SET deleted_at=now() FROM (SELECT set_config('request.jwt.claims','{\"sub\":\""+uid(1)+"\"}',false)) a");
  deny(5,'UPDATE case_tasks SET deleted_at=NULL');
  for (const n of [1,2]) assert.equal(run(n,'WITH x AS (UPDATE case_tasks SET deleted_at=NULL RETURNING id) SELECT count(*) FROM x'),'1');
  sql("SET request.jwt.claims='{"+'"sub":"'+uid(1)+'"'+"}'; UPDATE case_tasks SET deleted_at=NULL;");
});

