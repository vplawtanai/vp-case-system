test('097 changes only approved security objects; all Case/history/counter rows and Finance canary preserved', () => {
  assert.deepEqual(json(A.rows()),beforeRows);
  assert.equal(sql("SELECT facts->>'untouched' FROM finance_case097_preservation_canary"),'true');
  for (const sig of Object.keys(A.before.functions).filter(s => s !== 'can_create_case()')) assert.deepEqual(afterContract.functions[sig],A.before.functions[sig]);
  for (const n of A.names) for (const key of ['columns','constraints','indexes','owner']) assert.deepEqual(afterContract.tables[n][key],A.before.tables[n][key]);
  assert.deepEqual(afterContract,JSON.parse(A.read(A.afterPath)));
});

