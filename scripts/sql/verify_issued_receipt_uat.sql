        count(*) filter (where exists (
          select 1 from jsonb_each_text(to_jsonb(record)) field
          where field.key = any(%L::text[]) and field.value = any(%L::text[])
        )) as linked_rows,
        count(*) filter (where position(%L in to_jsonb(record)::text) > 0
