    'a76cd43d-fe52-4008-ade1-f1d79a9f27bf'::uuid as receipt_id,
    'VP-RC-202609-000001'::text as receipt_no,
    '9e2f601e-13ef-4165-8e2c-1887c3ad8861'::uuid as payment_id,
    '74461042-e3ba-4922-9b64-55aac9ebd8aa'::uuid as invoice_id,
    'VP-IV-202609-000003'::text as invoice_no,
    '2026-09-05'::date as received_date,
    '2026-09-07'::date as bangkok_issue_date,
    4859.81::numeric as cash, 140.19::numeric as wht,
    5000.00::numeric as settlement, 'THB'::text as currency
),
target_receipt as (
  select r.* from public.finance_receipts r join constants c on r.id = c.receipt_id
),
target_payment as (
  select p.* from public.finance_payments p join constants c on p.id = c.payment_id
),
target_invoice as (
  select i.* from public.finance_invoices i join constants c on i.id = c.invoice_id
