-- Final issued Receipt UAT: ONE read-only statement / ONE result row. No RPCs.
-- Run manually in SQL Editor with unrestricted read access (including Storage).
-- Receipt schema 2 / allocations / audit: migrations 037 and 038.
-- Optional downstream relations are catalog-discovered. query_to_xml runs only
-- the quoted SELECT below; identifiers/literals are escaped with format().
-- No live company/signer fallback, asset download, or lifecycle invocation.
-- Global Ledger/Compensation/Receipt counts are observability, never pass gates.
-- Catalog evidence cannot prove stored bytes are downloadable, or attribute an
-- unlinked external write. Human Preview and existing 038 retention guards apply.

with
