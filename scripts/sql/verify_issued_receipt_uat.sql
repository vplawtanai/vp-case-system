logo_facts as (
  -- Resolve ONLY the frozen reference. Current Document Settings is not queried.
  select count(*) filter (where
      r.issued_snapshot_json #>> '{seller,logo_asset,bucket}' = 'vp-document-assets'
      and r.issued_snapshot_json #>> '{seller,logo_asset,path}' ~ '^company/logo/[^/]+$'
      and r.issued_snapshot_json #>> '{seller,logo_asset,path}' not like '%..%'
      and nullif(btrim(r.issued_snapshot_json #>> '{seller,logo_asset,storage_version}'), '') is not null
      and o.id is not null and b.public = false
      and lower(coalesce(o.metadata->>'mimetype', '')) in ('image/png','image/jpeg','image/webp','image/svg+xml')
      and r.issued_snapshot_json #> '{seller,logo_asset}' = jsonb_build_object(
        'bucket', o.bucket_id, 'path', o.name, 'object_id', o.id,
        'storage_version', to_jsonb(o)->>'version')
    ) = 1 as frozen_logo_matches_storage_catalog_without_live_fallback,
    jsonb_agg(jsonb_build_object('object_id', o.id, 'bucket', o.bucket_id,
      'path', o.name, 'storage_version', to_jsonb(o)->>'version',
      'mimetype', o.metadata->>'mimetype')) as storage_evidence
  from target_receipt r
  left join storage.objects o on o.id::text = r.issued_snapshot_json #>> '{seller,logo_asset,object_id}'
    and o.bucket_id = r.issued_snapshot_json #>> '{seller,logo_asset,bucket}'
    and o.name = r.issued_snapshot_json #>> '{seller,logo_asset,path}'
  left join storage.buckets b on b.id = o.bucket_id
